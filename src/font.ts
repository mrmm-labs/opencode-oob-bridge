/** Characters the font does not have are drawn as this box, and the wrap marker is this arrow. */
const BOX = "000000" + "7e42424242424242427e" + "000000"
const WRAP = "000000" + "0202022262fe6020" + "0000000000"

export const WRAP_MARK = "\u21aa"
export const COLS = 8
export const ROWS_PER_GLYPH = 16

function codes(): number[] {
  const out: number[] = []
  for (let c = 0x20; c <= 0x7e; c++) out.push(c)
  for (let c = 0xa0; c <= 0xff; c++) out.push(c)
  return out
}

const GLYPHS = new Map<number, Uint8Array>(
  codes().map((c, i) => [
    c,
    Uint8Array.from(ROWS[i].match(/../g)!.map((h) => parseInt(h, 16))),
  ]),
)
GLYPHS.set(
  0x21aa,
  Uint8Array.from(WRAP.match(/../g)!.map((h) => parseInt(h, 16))),
)
const BOX_GLYPH = Uint8Array.from(BOX.match(/../g)!.map((h) => parseInt(h, 16)))

/** The 16 rows of a character; a box for one the font does not have. */
export function glyph(code: number): Uint8Array {
  return GLYPHS.get(code) ?? BOX_GLYPH
}

/** Whether the font draws this character itself. */
export function hasGlyph(code: number): boolean {
  return GLYPHS.has(code)
}
